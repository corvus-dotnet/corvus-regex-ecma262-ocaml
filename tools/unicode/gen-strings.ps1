<#
.SYNOPSIS
    Writes src/strings_tables<major>.ml, the properties of strings of one version of Unicode for the engine.

.DESCRIPTION
    The properties of strings (RGI_Emoji and the six it is the union of) are what only the v flag can name. This
    script copies them from strings<major>.rs of the corvus-regex-ecma262 Rust crate, so every engine holds the same
    Unicode emoji sequences. The engine carries Unicode 13, 17 and 18, a module for each. Each property is its name, its single code points as hexadecimal ranges, and its
    sequences as hexadecimal code points, a space between the code points of a sequence and a semicolon between
    sequences. A long string is written over several lines with OCaml's escaped line break, which drops the line break
    and the indentation after it.

.PARAMETER CrateStrings
    The path of corvus-regex-ecma262/src/strings<major>.rs in a checkout of the Rust crate.

.PARAMETER Output
    The file to write. The default is src/strings_tables<major>.ml of this repository.

.PARAMETER Check
    Compares what would be written with the file in place and writes nothing. The script fails when they differ.
#>
param(
    [Parameter(Mandatory = $true)][string]$CrateStrings,
    [string]$Output = '',
    [switch]$Check
)

$ErrorActionPreference = 'Stop'
$source = [System.IO.File]::ReadAllText((Resolve-Path $CrateStrings))
$version = [regex]::Match($source, 'pub\(crate\) const VERSION: &str = "([^"]+)";').Groups[1].Value
$body = [regex]::Match($source, 'pub\(crate\) static PROPERTIES: \[\(&str, &str, &str\); \d+\] = \[(.*?)\n\];', 'Singleline')
if (-not $version -or -not $body.Success) { throw "The strings file of the crate has changed shape. The generator needs updating for it." }
$rows = @([regex]::Matches($body.Groups[1].Value, '\("([^"]*)", "([^"]*)", "([^"]*)"\),'))
if ($rows.Count -eq 0) { throw 'The strings file of the crate has no rows in PROPERTIES.' }
$major = $version.Split('.')[0]
if (-not $Output) { $Output = Join-Path (Join-Path (Split-Path (Split-Path $PSScriptRoot -Parent) -Parent) 'src') "strings_tables$major.ml" }
$sourceName = Split-Path $CrateStrings -Leaf

$out = [System.Text.StringBuilder]::new()
function Add-Line([string]$line = '') { [void]$out.Append($line).Append("`n") }

# Writes a string literal as pieces of at most 100 characters, each cut after a space or a semicolon where there is one,
# every piece but the last ended by an escaped line break. A piece keeps the space it was cut after, before the break.
function Add-Pieces([string]$indent, [string]$value, [string]$end) {
    if ($value.Length -eq 0) { Add-Line "$indent`"`"$end"; return }
    $pieces = [System.Collections.Generic.List[string]]::new()
    $at = 0
    while ($at -lt $value.Length) {
        $n = [Math]::Min(100, $value.Length - $at)
        if ($at + $n -lt $value.Length) {
            $cut = $value.LastIndexOfAny([char[]]@(' ', ';'), $at + $n - 1, $n)
            if ($cut -gt $at) { $n = $cut - $at + 1 }
        }
        $pieces.Add($value.Substring($at, $n))
        $at += $n
    }
    for ($k = 0; $k -lt $pieces.Count; $k++) {
        $open = if ($k -eq 0) { "$indent`"" } else { "$indent " }
        $tail = if ($k -eq $pieces.Count - 1) { "`"$end" } else { '\' }
        Add-Line "$open$($pieces[$k])$tail"
    }
}

Add-Line "(* Code generated by tools/unicode/gen-strings.ps1 from $sourceName of the corvus-regex-ecma262 Rust crate"
Add-Line "   (emoji-sequences.txt and emoji-zwj-sequences.txt of Unicode $version). DO NOT EDIT. *)"
Add-Line
Add-Line '(* The version of Unicode the properties of strings are from. *)'
Add-Line "let version = `"$version`""
Add-Line
Add-Line '(* Each property of strings but RGI_Emoji (the union of them all): its name, its single code points as hexadecimal'
Add-Line '   ranges, and its sequences as hexadecimal code points, a space between the code points of a sequence and a semicolon'
Add-Line '   between sequences. *)'
Add-Line 'let properties ='
Add-Line '  [|'
for ($k = 0; $k -lt $rows.Count; $k++) {
    $end = if ($k -eq $rows.Count - 1) { '' } else { ';' }
    Add-Line "    ( `"$($rows[$k].Groups[1].Value)`","
    Add-Pieces '      ' $rows[$k].Groups[2].Value ','
    Add-Pieces '      ' $rows[$k].Groups[3].Value " )$end"
}
Add-Line '  |]'

$text = $out.ToString().TrimEnd("`n") + "`n"
foreach ($line in $text -split "`n") {
    if ($line.Length -gt 120) { throw "A line of the output is longer than 120 characters: $line" }
}
if ($Check) {
    $current = if (Test-Path $Output) { [System.IO.File]::ReadAllText($Output) } else { '' }
    if ($current -ne $text) { throw "$Output is not what $CrateStrings generates. Run tools/unicode/gen-strings.ps1." }
    Write-Host "$Output is current ($($rows.Count) properties)."
    return
}
[System.IO.File]::WriteAllText($Output, $text, [System.Text.UTF8Encoding]::new($false))
Write-Host "Wrote $Output with $($rows.Count) properties of strings, Unicode $version."
