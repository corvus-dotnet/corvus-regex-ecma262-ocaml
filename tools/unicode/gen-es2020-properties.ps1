<#
.SYNOPSIS
    Writes src/es2020.ml, the Unicode property names and values of the tables of ECMAScript 2020.

.DESCRIPTION
    The grammar of ECMAScript 2020 knows only the property names and values of its own tables, whatever the version of
    Unicode. This script copies them from es2020.rs of the corvus-regex-ecma262 Rust crate, so every engine's 2020
    grammar knows the same names. Each list is an OCaml match over strings.

.PARAMETER CrateEs2020
    The path of corvus-regex-ecma262/src/es2020.rs in a checkout of the Rust crate.

.PARAMETER Output
    The file to write. The default is src/es2020.ml of this repository.

.PARAMETER Check
    Compares what would be written with the file in place and writes nothing. The script fails when they differ.
#>
param(
    [Parameter(Mandatory = $true)][string]$CrateEs2020,
    [string]$Output = (Join-Path (Join-Path (Split-Path (Split-Path $PSScriptRoot -Parent) -Parent) 'src') 'es2020.ml'),
    [switch]$Check
)

$ErrorActionPreference = 'Stop'
$source = [System.IO.File]::ReadAllText((Resolve-Path $CrateEs2020))

function Get-Names([string]$rustFn) {
    $m = [regex]::Match($source, "fn $rustFn\(name: &str\) -> bool \{\s*matches!\(\s*name,(.*?)\)\s*\}", 'Singleline')
    if (-not $m.Success) { throw "es2020.rs has no $rustFn. The generator needs updating for the crate's file." }
    $names = @([regex]::Matches($m.Groups[1].Value, '"([^"]*)"') | ForEach-Object { $_.Groups[1].Value })
    if ($names.Count -eq 0) { throw "es2020.rs lists no names in $rustFn." }
    return , $names
}

$out = [System.Text.StringBuilder]::new()
function Add-Line([string]$line = '') { [void]$out.Append($line).Append("`n") }

# Writes the patterns of a match, as many to a line as fit in 120 columns.
function Add-Patterns([string[]]$names) {
    $row = [System.Text.StringBuilder]::new('  |')
    foreach ($n in $names) {
        $item = " `"$n`""
        if ($row.Length -gt 3 -and $row.Length + $item.Length + 2 -gt 120) {
            Add-Line $row.ToString()
            $row = [System.Text.StringBuilder]::new('  |')
        } elseif ($row.Length -gt 3) {
            [void]$row.Append(' |')
        }
        [void]$row.Append($item)
    }
    Add-Line ($row.ToString() + ' ->')
}

function Add-Matcher([string]$name, [string]$doc, [string[]]$names) {
    Add-Line "(* $doc *)"
    Add-Line "let $name = function"
    Add-Patterns $names
    Add-Line '      true'
    Add-Line '  | _ -> false'
    Add-Line
}

Add-Line '(* Code generated by tools/unicode/gen-es2020-properties.ps1 from es2020.rs of the corvus-regex-ecma262 Rust crate.'
Add-Line '   DO NOT EDIT.'
Add-Line
Add-Line '   The Unicode property names and values of the tables of ECMAScript 2020 (ECMA-262, 11th edition), the only ones'
Add-Line '   its grammar knows whatever the version of Unicode: tc39/ecma262 at the tag es2020, every name and alias of each. *)'
Add-Line
$count = 0
foreach ($m in @(@('non_binary', 'The non-binary properties.'), @('binary', 'The binary properties.'),
        @('category', 'The General_Category values.'), @('script', 'The Script values.'))) {
    $names = Get-Names $m[0]
    $count += $names.Count
    Add-Matcher $m[0] $m[1] $names
}
Add-Line '(* Whether the expression between the braces of \p{...} names a property, and a value of it, of the tables: a name'
Add-Line '   and a value joined by =, or the lone name of a General_Category value or of a binary property. *)'
Add-Line 'let has_property expr ='
Add-Line '  match String.index_opt expr ''='' with'
Add-Line '  | None -> category expr || binary expr'
Add-Line '  | Some k -> ('
Add-Line '      let name = String.sub expr 0 k and value = String.sub expr (k + 1) (String.length expr - k - 1) in'
Add-Line '      match name with'
Add-Line '      | "General_Category" | "gc" -> category value'
Add-Line '      | _ -> non_binary name && script value)'

$text = $out.ToString().TrimEnd("`n") + "`n"
foreach ($line in $text -split "`n") {
    if ($line.Length -gt 120) { throw "A line of the output is longer than 120 characters: $line" }
}
if ($Check) {
    $current = if (Test-Path $Output) { [System.IO.File]::ReadAllText($Output) } else { '' }
    if ($current -ne $text) { throw "$Output is not what $CrateEs2020 generates. Run tools/unicode/gen-es2020-properties.ps1." }
    Write-Host "$Output is current ($count names)."
    return
}
[System.IO.File]::WriteAllText($Output, $text, [System.Text.UTF8Encoding]::new($false))
Write-Host "Wrote $Output with $count names."
